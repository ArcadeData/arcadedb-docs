#!/usr/bin/env python3
"""
Replace the build timestamp Antora writes into every sitemap <lastmod> with
the date of the last git commit that touched the page's source.

Antora stamps every entry with the time of the build, so all URLs look
changed on every deploy and search engines ignore the field. The docs pages
are generated by migrate.sh from src/main/asciidoc/ (and a few templates in
scripts/templates/), so the commit history of those files is the real
change date.

URLs whose source is not in this repository (the arcadedb-python component)
get no <lastmod> rather than a fake one. On a shallow clone every file would
share one commit date, so the script leaves the sitemaps untouched; CI
checks out the full history (fetch-depth: 0) for this.

Usage: scripts/sitemap-lastmod.py build/site
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SITE_URL = "https://docs.arcadedb.com"
COMPONENT = "arcadedb"

# Antora page path (relative to docs/modules/ROOT/pages) -> source in this repo.
TEMPLATE_SOURCES = {
    "index.adoc": "scripts/templates/index.adoc",
    "get-started.adoc": "scripts/templates/get-started.adoc",
}

URL_RE = re.compile(r"<url>(.*?)</url>", re.S)
LOC_RE = re.compile(r"<loc>([^<]+)</loc>")
LASTMOD_RE = re.compile(r"\s*<lastmod>[^<]*</lastmod>")


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, check=True, capture_output=True, text=True).stdout


def last_commit_dates() -> dict[str, str]:
    """Path -> ISO date of the newest commit touching it, in one git log pass."""
    out = git("log", "--format=@%cI", "--name-only", "--", "src/main/asciidoc", "scripts/templates")
    dates: dict[str, str] = {}
    current = None
    for line in out.splitlines():
        if line.startswith("@"):
            current = line[1:]
        elif line and current:
            dates.setdefault(line, current)
    return dates


def source_for(url: str) -> str | None:
    prefix = f"{SITE_URL}/{COMPONENT}/"
    if not url.startswith(prefix):
        return None
    path = url[len(prefix):]
    page = (path + "index" if path == "" or path.endswith("/") else path) + ".adoc"
    return TEMPLATE_SOURCES.get(page, f"src/main/asciidoc/{page}")


def main() -> int:
    site = Path(sys.argv[1] if len(sys.argv) > 1 else "build/site")
    if git("rev-parse", "--is-shallow-repository").strip() == "true":
        print("sitemap-lastmod: shallow clone, keeping Antora's lastmod values", file=sys.stderr)
        return 0
    dates = last_commit_dates()
    dated = undated = 0
    for sitemap in sorted(site.glob("sitemap-*.xml")):
        def fix(m: re.Match[str]) -> str:
            nonlocal dated, undated
            body = m.group(1)
            loc = LOC_RE.search(body)
            src = source_for(loc.group(1)) if loc else None
            body = LASTMOD_RE.sub("", body)
            if src and src in dates:
                dated += 1
                body = body.replace("</loc>", f"</loc>\n<lastmod>{dates[src]}</lastmod>", 1)
            else:
                undated += 1
            return f"<url>{body}</url>"

        text = sitemap.read_text(encoding="utf-8")
        sitemap.write_text(URL_RE.sub(fix, text), encoding="utf-8")
    print(f"sitemap-lastmod: {dated} URLs dated from git, {undated} without lastmod")
    return 0


if __name__ == "__main__":
    sys.exit(main())
